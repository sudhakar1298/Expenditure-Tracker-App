from pyspark.sql import SparkSession
from databricks.config import config, load_spark_df_safely

EMAIL_TEMPLATE = """<!DOCTYPE html>
<html>
<head>
    <style>
        body {{ font-family: Arial, sans-serif; background-color: #0f172a; color: #f8fafc; padding: 20px; }}
        .card {{ background-color: #1e293b; border-radius: 12px; padding: 20px; margin-bottom: 20px; border: 1px solid #334155; }}
        h1 {{ color: #6366f1; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 10px; }}
        th, td {{ padding: 10px; text-align: left; border-bottom: 1px solid #334155; }}
        th {{ color: #94a3b8; font-size: 12px; text-transform: uppercase; }}
        .amount {{ text-align: right; font-weight: bold; color: #10b981; }}
    </style>
</head>
<body>
    <div class="card">
        <h1>📊 Weekly Financial Executive Summary</h1>
        <p>Automated report generated by Databricks Medallion Pipeline.</p>
        <h2>Total Spent: <span style="color: #6366f1;">₹{total_spent}</span></h2>
        <p>Total Transactions Logged: {transaction_count}</p>
    </div>

    <div class="card">
        <h3>Top Categories</h3>
        <table>
            <thead>
                <tr>
                    <th>Category</th>
                    <th>Transactions</th>
                    <th style="text-align: right;">Spent (₹)</th>
                </tr>
            </thead>
            <tbody>
                {category_rows}
            </tbody>
        </table>
    </div>
</body>
</html>
"""

def generate_weekly_email_report(spark: SparkSession) -> str:
    category_df = load_spark_df_safely(spark, config.GOLD_CATEGORY_PATH)
    categories = [row.asDict() for row in category_df.collect()]

    total_spent = sum(c["total_spent"] for c in categories) if categories else 0.0
    transaction_count = sum(c["transaction_count"] for c in categories) if categories else 0

    category_rows_html = ""
    for cat in categories:
        category_rows_html += f"""
        <tr>
            <td>{cat.get('category', 'Others')}</td>
            <td>{cat.get('transaction_count', 0)}</td>
            <td class="amount">₹{cat.get('total_spent', 0.0):,.2f}</td>
        </tr>
        """

    html_content = EMAIL_TEMPLATE.format(
        total_spent=f"{total_spent:,.2f}",
        transaction_count=transaction_count,
        category_rows=category_rows_html
    )

    print("[Report Job] Weekly email HTML generated successfully.")
    return html_content
